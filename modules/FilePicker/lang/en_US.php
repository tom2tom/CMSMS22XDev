<h3>What does this do?</h3>
<p>This module allows authorized admin editors to select a file e.g. to select an image for use in a WYSIWYG field, or to associate an image or thumbnail with a page, or attach a PDF file to a news article.  The module also has a small amount of ancillary functionality to allow authorized users to upload and delete files, or to create and remove subdirectories.</p>
<p>This module also allows for the creation of multiple profiles with different capabilities. Profiles can be used by the <code>{cms_filepicker}</code> plugin or by the module's &quot;select&quot; action when definining how the picker should behave. Other module parameters, or user permissions can override the settings defined in the profile.</p>

<h3>How Do I Use It</h3>
<p>This module is intended to be used in the core or by other modules, via various core API's.  And via the {cms_filepicker} plugin.</p>
<p>Additionally, this module can be called directly via the <code>{cms_module module=FilePicker action=select name=string [profile=string] [type=string] [value=string]}</code> tag, but that is not recommended.  See the {cms_filepicker} tag for information about the type, and other parameters.</p>
<br>
<p>Authorised users may review, add and modify profiles, in the Site Admin > Settings - Uploads page.</p>

<h3>Content Block for Page Templates</h3>
<p>This module also provides a content block to enable a file-picker to be used in page templates. This can, for example, be used as an alternative to the {content_image} plugin.</p>
<p><code>{content_module module=FilePicker block=string [profile=string] [format=string]}</code></p>
<p>By default the file-picker generates a site-root-url-relative urlpath. The optional format parameter allows that to be tailored when displaying the block. Recognised values are 'absolute', 'anchor' and 'image'. The latter two initiate creation of corresponding html elelements.</p>
<p>The standard 'content_module' plugin parameters: module, block, adminonly, label, required, tab, priority and assign are also usable, of course.</p>

